function metrics = export_tracking_report(prefix, title_text, time, position, reference, lateral, longitudinal, yaw, speed, omega)
% Replacement reporting helper: returns and writes RMS/max errors plus raw data.
count = size(lateral, 2);
metrics = table((1:count)', sqrt(mean(lateral.^2,1))', max(abs(lateral),[],1)', ...
    sqrt(mean(longitudinal.^2,1))', max(abs(longitudinal),[],1)', ...
    sqrt(mean(yaw.^2,1))', max(abs(yaw),[],1)', ...
    'VariableNames', {'Ship','LateralRMS_m','LateralMax_m', ...
    'LongitudinalRMS_m','LongitudinalMax_m','YawRMS_rad','YawMax_rad'});
writetable(metrics, [prefix '_tracking_metrics.csv']);
save([prefix '_tracking_data.mat'], 'title_text', 'time', 'position', ...
    'reference', 'lateral', 'longitudinal', 'yaw', 'speed', 'omega');
end
